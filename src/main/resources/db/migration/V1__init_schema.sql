CREATE TABLE docente (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome varchar(30) NOT NULL,
    cognome varchar(30) NOT NULL,
    email varchar(50) NOT NULL UNIQUE,
    settore varchar(80)
);

CREATE TABLE studente (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome varchar(30) NOT NULL,
    cognome varchar(30) NOT NULL,
    email varchar(50) NOT NULL UNIQUE,
    matricola varchar(50) NOT NULL UNIQUE
);

CREATE TABLE corso (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    titolo varchar(30) NOT NULL,
    descrizione varchar(255),
    cfu integer NOT NULL,
    docente_id integer,
    CONSTRAINT fk_corso_docente
        FOREIGN KEY (docente_id)
        REFERENCES docente(id)
        ON DELETE SET NULL
);

CREATE TABLE iscrizione (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    studente_id integer NOT NULL,
    corso_id integer NOT NULL,
    CONSTRAINT uk_iscrizione_studente_corso UNIQUE (studente_id, corso_id),
    CONSTRAINT fk_iscrizione_studente
        FOREIGN KEY (studente_id)
        REFERENCES studente(id)
        ON DELETE CASCADE,
    CONSTRAINT fk_iscrizione_corso
        FOREIGN KEY (corso_id)
        REFERENCES corso(id)
        ON DELETE CASCADE
);

CREATE INDEX idx_corso_docente_id ON corso(docente_id);
CREATE INDEX idx_iscrizione_studente_id ON iscrizione(studente_id);
CREATE INDEX idx_iscrizione_corso_id ON iscrizione(corso_id);
